var (
	errInvalidPath    = errors.New("invalid shared path")
	errFolderNotEmpty = errors.New("folder is not empty")
	errFileChanged    = errors.New("file or folder changed")
)

const stagingPrefix = ".landrop-upload-"

func cleanupUploadStaging(root *os.Root) (int, error) {
	entries, err := fs.ReadDir(root.FS(), ".")
	if err != nil {
		return 0, err
	}
	var removed int
	var failures []error
	for _, entry := range entries {
		name := entry.Name()
		suffix, ok := strings.CutPrefix(name, stagingPrefix)
		// The suffix is the lowercase base32 token generated by rand.Text.
		if !ok || len(suffix) < 26 || strings.ContainsFunc(suffix, func(r rune) bool {
			return !strings.ContainsRune("abcdefghijklmnopqrstuvwxyz234567", r)
		}) {
			continue
		}
		info, err := entry.Info()
		if err == nil && info.Mode().IsRegular() {
			err = root.Remove(name)
			if err == nil {
				removed++
			}
		}
		if err != nil && !errors.Is(err, fs.ErrNotExist) {
			failures = append(failures, err)
		}
	}
	return removed, errors.Join(failures...)
}

var uploadBuffers = sync.Pool{New: func() any {
	return new([256 << 10]byte)
}}

type fileItem struct {
	ID        string    `json:"id"`
	Version   string    `json:"version"`
	Name      string    `json:"name"`
	Path      string    `json:"path"`
	Directory bool      `json:"directory"`
	Size      int64     `json:"size"`
	Modified  time.Time `json:"modified"`
}

type fileStore struct {
	root *os.Root
	mu   sync.Mutex
}

func validName(name string) bool {
	if !utf8.ValidString(name) || !filepath.IsLocal(name) || len(name) > 240 ||
		strings.ContainsAny(name, "/\\:<>\"|?*") || strings.HasSuffix(name, ".") ||
		strings.TrimSpace(name) != name || strings.HasPrefix(strings.ToLower(name), stagingPrefix) ||
		strings.IndexFunc(name, unicode.IsControl) >= 0 {
		return false
	}
	base, _, _ := strings.Cut(strings.ToUpper(name), ".")
	base = strings.TrimRight(base, " ")
	switch base {
	case "CON", "PRN", "AUX", "NUL", "CONIN$", "CONOUT$":
		return false
	}
	if suffix, ok := strings.CutPrefix(base, "COM"); ok && strings.Contains("123456789¹²³", suffix) && utf8.RuneCountInString(suffix) == 1 {
		return false
	}
	if suffix, ok := strings.CutPrefix(base, "LPT"); ok && strings.Contains("123456789¹²³", suffix) && utf8.RuneCountInString(suffix) == 1 {
		return false
	}
	return name != "." && name != ".."
}

func validPath(name string) bool {
	if len(name) > 4096 {
		return false
	}
	parts := strings.Split(name, "/")
	if len(parts) > 32 {
		return false
	}
	for _, part := range parts {
		if !validName(part) {
			return false
		}
	}
	return true
}

func decodeID(id string) (string, error) {
	raw, err := base64.RawURLEncoding.DecodeString(id)
	if err != nil || !validPath(string(raw)) {
		return "", errInvalidPath
	}
	return string(raw), nil
}

func (s *fileStore) describeFile(name string, info os.FileInfo) fileItem {
	// Keep the entry visible if the filesystem cannot provide its identity.
	version, _ := s.fileVersion(name, info)
	return fileItem{
		ID: base64.RawURLEncoding.EncodeToString([]byte(name)), Name: path.Base(name),
		Path: name, Directory: info.IsDir(), Size: info.Size(), Modified: info.ModTime(), Version: version,
	}
}

func (s *fileStore) fileVersion(name string, info os.FileInfo) (string, error) {
	identity, err := fileIdentity(s.root, name, info)
	if err != nil {
		return "", err
	}
	metadata := fmt.Sprintf("%s:%d:%d:%t", identity, info.ModTime().UnixNano(), info.Size(), info.IsDir())
	sum := sha256.Sum256([]byte(metadata))
	return base64.RawURLEncoding.EncodeToString(sum[:]), nil
}

// directory checks each component without accepting links. os.Root also
// confines the filesystem calls if the host changes a path concurrently.
func (s *fileStore) directory(dir string, onCreate func(string)) error {
	if dir == "." {
		return nil
	}
	if !validPath(dir) {
		return errInvalidPath
	}
	current := ""
	for part := range strings.SplitSeq(dir, "/") {
		current = path.Join(current, part)
		info, err := s.root.Lstat(current)
		if onCreate != nil && errors.Is(err, os.ErrNotExist) {
			if err := s.root.Mkdir(current, 0700); err != nil {
				return err
			}
			onCreate(current)
			continue
		}
		if err != nil {
			return err
		}
		if !info.IsDir() {
			return os.ErrNotExist
		}
	}
	return nil
}

func (s *fileStore) listFolder(dir string) ([]fileItem, error) {
	if dir == "" {
		dir = "."
	} else if !validPath(dir) {
		return nil, errInvalidPath
	}
	if err := s.directory(dir, nil); err != nil {
		return nil, err
	}
	entries, err := fs.ReadDir(s.root.FS(), dir)
	if err != nil {
		return nil, err
	}
	items := []fileItem{}
	for _, entry := range entries {
		if !validName(entry.Name()) {
			continue
		}
		info, err := entry.Info()
		if err == nil && (info.Mode().IsRegular() || info.IsDir()) {
			items = append(items, s.describeFile(path.Join(dir, entry.Name()), info))
		}
	}
	slices.SortStableFunc(items, func(a, b fileItem) int {
		if a.Directory != b.Directory {
			if a.Directory {
				return -1
			}
			return 1
		}
		if a.Directory {
			return strings.Compare(a.Name, b.Name)
		}
		return b.Modified.Compare(a.Modified)
	})
	return items, nil
}

func (s *fileStore) entry(name string) (os.FileInfo, error) {
	if err := s.directory(path.Dir(name), nil); err != nil {
		return nil, err
	}
	info, err := s.root.Lstat(name)
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() && !info.IsDir() {
		return nil, os.ErrNotExist
	}
	return info, nil
}

// Call with s.mu held so LanDrop operations cannot replace the entry after verification.
func (s *fileStore) entryForChange(name, ifMatch string) (os.FileInfo, error) {
	info, err := s.entry(name)
	if ifMatch == "" {
		return info, err
	}
	if errors.Is(err, os.ErrNotExist) {
		return nil, errFileChanged
	}
	if err != nil {
		return nil, err
	}
	version, err := s.fileVersion(name, info)
	if errors.Is(err, os.ErrNotExist) {
		return nil, errFileChanged
	}
	if err != nil {
		return nil, err
	}
	if ifMatch != `"`+version+`"` {
		return nil, errFileChanged
	}
	return info, nil
}

func (s *fileStore) open(id string) (*os.File, os.FileInfo, error) {
	name, err := decodeID(id)
	if err != nil {
		return nil, nil, err
	}
	info, err := s.entry(name)
	if err != nil || !info.Mode().IsRegular() {
		return nil, nil, os.ErrNotExist
	}
	file, err := s.root.Open(name)
	if err != nil {
		return nil, nil, err
	}
	opened, err := file.Stat()
	if err != nil || !os.SameFile(info, opened) {
		file.Close()
		return nil, nil, os.ErrNotExist
	}
	return file, opened, nil
}

func (s *fileStore) mkdir(name string) error {
	if !validPath(name) {
		return errInvalidPath
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.directory(path.Dir(name), nil); err != nil {
		return err
	}
	return s.root.Mkdir(name, 0700)
}

func (s *fileStore) move(id, target, ifMatch string) error {
	source, err := decodeID(id)
	if err != nil || !validPath(target) {
		return errInvalidPath
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	info, err := s.entryForChange(source, ifMatch)
	if err != nil {
		return err
	}
	if source == target {
		return nil
	}
	if info.IsDir() && strings.HasPrefix(strings.ToLower(target), strings.ToLower(source)+"/") {
		return errInvalidPath
	}
	if err := s.directory(path.Dir(target), nil); err != nil {
		return err
	}
	_, err = s.root.Lstat(target)
	if err == nil {
		return os.ErrExist
	}
	if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return s.root.Rename(source, target)
}

func (s *fileStore) remove(id string, recursive bool, ifMatch string) error {
	name, err := decodeID(id)
	if err != nil {
		return err
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	info, err := s.entryForChange(name, ifMatch)
	if err != nil {
		return err
	}
	if info.IsDir() {
		if recursive {
			return s.root.RemoveAll(name)
		}
		dir, err := s.root.Open(name)
		if err != nil {
			return err
		}
		_, err = dir.Readdirnames(1)
		dir.Close()
		if err == nil {
			return errFolderNotEmpty
		}
		if !errors.Is(err, io.EOF) {
			return err
		}
	}
	return s.root.Remove(name)
}

func copyUpload(file *os.File, body io.Reader, size int64) error {
	if size >= 0 && size < 1<<20 {
		_, err := io.Copy(file, body)
		return err
	}
	buffer := uploadBuffers.Get().(*[256 << 10]byte)
	defer uploadBuffers.Put(buffer)
	// Use the supplied buffer instead of os.File.ReadFrom's fallback buffer.
	_, err := io.CopyBuffer(struct{ io.Writer }{file}, body, buffer[:])
	return err
}

func (s *fileStore) save(name string, body io.Reader, size int64) (fileItem, []string, error) {
	var created []string
	if !validPath(name) {
		return fileItem{}, created, errInvalidPath
	}
	temp := stagingPrefix + strings.ToLower(rand.Text())
	file, err := s.root.OpenFile(temp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return fileItem{}, created, err
	}
	defer s.root.Remove(temp)
	copyErr := copyUpload(file, body, size)
	closeErr := file.Close()
	if err := errors.Join(copyErr, closeErr); err != nil {
		return fileItem{}, created, err
	}

	s.mu.Lock()
	defer s.mu.Unlock()
	dir := path.Dir(name)
	if err := s.directory(dir, func(path string) { created = append(created, path) }); err != nil {
		return fileItem{}, created, err
	}
	filename := path.Base(name)
	ext := path.Ext(filename)
	base := strings.TrimSuffix(filename, ext)
	candidate := name
	for i := 0; i < 1000; i++ {
		_, err := s.root.Lstat(candidate)
		if errors.Is(err, os.ErrNotExist) {
			if err := s.root.Rename(temp, candidate); err != nil {
				return fileItem{}, created, err
			}
			info, err := s.root.Stat(candidate)
			if err != nil {
				return fileItem{}, created, err
			}
			return s.describeFile(candidate, info), created, nil
		}
		if err != nil {
			return fileItem{}, created, err
		}
		suffix := fmt.Sprintf(" (%d)%s", i+1, ext)
		if len(suffix) > 120 {
			suffix = fmt.Sprintf(" (%d)", i+1)
			base = filename
		}
		for len(base)+len(suffix) > 240 {
			_, length := utf8.DecodeLastRuneInString(base)
			base = base[:len(base)-length]
		}
		candidate = path.Join(dir, base+suffix)
	}
	return fileItem{}, created, fmt.Errorf("too many files with this name")
}
