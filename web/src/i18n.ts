function translate(language: Language, message: string, values?: Record<string, string | number>) {
  const template = language === 'zh-CN' && Object.hasOwn(chinese, message) ? chinese[message] : message
  return values ? template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match)) : template
}

const translators = {
  en: translate.bind(null, 'en'),
  'zh-CN': translate.bind(null, 'zh-CN'),
}

export function useTranslation() {
  return translators[useContext(LanguageContext)]
}
